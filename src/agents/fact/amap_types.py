# ── 判定函数 ──────────────────────────────────────────────────────────

def label_of(typecode: str | None) -> str:
    """把 typecode 翻译成人能读的类目名。

    这个函数的实际用途比看起来重要：候选池现在传给 PlanningAgent 的
    `type` 字段是 "050121" 这种裸编码，模型看到的是一串没有意义的
    数字——它既无法据此判断菜系，也无法据此响应用户的口味偏好。
    翻译成"清真菜馆"之后，模型才有可用的信息。

    未知码按前缀退化到中类（"0501xx" → "中餐厅"），再不行返回原码。
    不抛异常：码表滞后于高德更新是必然的，一个新码不该让整条链路崩。
    """
    if not typecode:
        return ""
    code = str(typecode).strip()
    if code in AMAP_FOOD_TYPES:
        return AMAP_FOOD_TYPES[code]
    mid = _MID_LEVEL.get(code[:4])
    return mid or code


def is_food(typecode: str | None) -> bool:
    """是不是餐饮类 POI。

    这是 `is_restaurant` 标注错误的结构性解药：现在餐厅/活动的
    归类完全依赖模型在搜索前的标注，标错了没有任何反馈（实测出现过
    "27 个活动 + 0 家餐厅"，而用户明确要吃饭）。typecode 是数据源
    自己给的事实，不需要模型判断，也就不会标错。
    """
    return bool(typecode) and str(typecode).strip().startswith(FOOD_PREFIX)


def spice_level(typecode: str | None) -> str:
    """返回 "spicy" | "mild" | "unknown"。

    unknown 是诚实的第三种答案，不是失败。把它强行归入 spicy 或
    mild 都是伪造确定性——火锅店在成都和昆明是两回事，码表给不出
    答案时就该说给不出。
    """
    code = (typecode or "").strip()
    if code in SPICY_TYPES:
        return "spicy"
    if code in MILD_TYPES:
        return "mild"
    return "unknown"


def violates_no_spicy(typecode: str | None, strict: bool = False) -> bool:
    """用户表达"不吃辣"时，这个 POI 该不该被排除。

    strict=False（默认）：只排除确定辣的（川菜、湘菜）。存疑的
        （火锅店、云贵菜）放行——搜索/过滤阶段的误杀不可逆，
        排掉了就再也不在候选池里，而放行的最坏结果只是模型可能
        选中一家用户不喜欢的店，用户还能在下一轮否决它。
        两种错误的代价不对称，所以默认偏宽松。

    strict=True：连存疑的一起排除。适合"用户已经因为吃到辣的
        抱怨过一次"这类场景——此时误杀的代价降低了，因为已经
        证明宽松策略在这个用户身上不成立。
    """
    level = spice_level(typecode)
    if level == "spicy":
        return True
    if strict and (typecode or "").strip() in SPICY_AMBIGUOUS_TYPES:
        return True
    return False


def is_chain(typecode: str | None) -> bool:
    """是不是**已知**连锁品牌。

    只能证实，不能证伪：命中即确定是连锁；不命中只说明这张表
    不认识它（海底捞、蜜雪冰城这些没有专属码）。所以不要写成
    `if not is_chain(x): 这是独立小店` —— 那是错的推断方向。
    """
    return (typecode or "").strip() in KNOWN_CHAIN_TYPES


def describe(typecode: str | None) -> dict:
    """一个 POI 的类目画像，给候选池渲染和断言共用一份口径。
    两处各写一遍判定逻辑迟早会漂移，这个仓库为"两本账"付过学费。"""
    code = (typecode or "").strip()
    return {
        "typecode": code,
        "label": label_of(code),
        "is_food": is_food(code),
        "spice": spice_level(code),
        "known_chain": is_chain(code),
    }