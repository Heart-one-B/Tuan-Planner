# agents/fact/amap_types.py
"""高德 POI 分类码表（餐饮部分）与基于它的偏好判定。

【为什么要这张表】
实测确认：搜索结果里没有 `type` 字段，只有 `typecode`，15/15 全覆盖。
而 typecode 是高德三级分类的六位码——这是**结构化的、由数据源自己
维护的**类目信息，比在店名上做关键词匹配可靠得多。

对照一下两种判定"这家店辣不辣"的方式：

  店名匹配   "爱尚菌·野生菌火锅" 含"火锅" → 判为辣 ❌（实际是菌汤）
             "正宗富源酸菜土猪脚火锅" → 判为辣 ❌（实际是酸菜）
             同一个词在云南和四川含义相反，无解。

  typecode   050117 = 火锅店（业态），050102 = 川菜（菜系）
             两者正交，歧义被显式定位到"火锅店辣不辣"这一个码上，
             而不是弥散在所有店名里。

【这张表能做什么、不能做什么 —— 必须分清】
高德的分类维度是「地域菜系 + 经营业态」，不是「食物品类」。
用户说"想吃凉皮/肉夹馍/炸鸡"，这些在码表里没有对应项
（最接近的是 050115 西北菜 / 050118 特色风味 / 050300 快餐厅，
都不精确）。所以：

  ✅ 负向排除    "不吃辣" → 排除 050102/050108，确定性判定
  ✅ 业态识别    "不要快餐" → 排除 0503xx
  ⚠️ 正向匹配    "想吃粤菜" → 只能作为关键词提示，因为
                 maps_around_search **没有 types 参数**（实测：
                 传 050102 和 050103 返回结果逐字相同），
                 类目无法进入检索条件，只能搜完再筛。

【码表会变，不要当成永久事实】
高德官方明确说编码表会不定期更新、建议不要把数字写死在程序里。
这里仍然写死，是因为：① 只用了最稳定的餐饮大类，十年没变过；
② 未知码有前缀兜底（见 label_of），新增的三级码会退化成中类标签
而不是崩溃；③ 引入运行时拉取码表的机制，成本远高于收益。
如果哪天判定开始出错，先来核对这张表。
"""
